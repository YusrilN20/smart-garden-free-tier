-- 1. Tabel riwayat sensor (CHECK = validasi data dari ESP32)
create table if not exists sensor_logs (
  id bigint generated by default as identity primary key,
  suhu real not null check (suhu between -40 and 80),
  kelembapan real not null check (kelembapan between 0 and 100),
  created_at timestamptz not null default now()
);
create index if not exists sensor_logs_created_at_idx on sensor_logs (created_at desc);

-- 2. Kunci perangkat (TIDAK bisa dibaca dari luar karena RLS tanpa policy)
create table if not exists device_keys (
  key text primary key check (length(key) >= 24)
);

-- 3. Konfigurasi MQTT untuk dashboard (hanya bisa dibaca user yang login)
create table if not exists app_config (
  id int primary key default 1 check (id = 1),
  mqtt_url text not null,       -- contoh: wss://broker.avisha.id:8084/mqtt
  mqtt_user text not null,
  mqtt_pass text not null,
  topic_prefix text not null    -- contoh: namauser/  (wajib diawali username Avisha)
);

alter table sensor_logs enable row level security;
alter table device_keys enable row level security;
alter table app_config enable row level security;

-- 4. Cek header x-device-key yang dikirim ESP32
create or replace function is_valid_device() returns boolean
language sql stable security definer set search_path = public as $$
  select exists (
    select 1 from device_keys
    where key = current_setting('request.headers', true)::json ->> 'x-device-key'
  );
$$;
revoke all on function is_valid_device() from public;
grant execute on function is_valid_device() to anon, authenticated;

-- 5. Policy: ESP32 (anon + kunci benar) boleh INSERT, user login boleh SELECT
drop policy if exists "device insert" on sensor_logs;
create policy "device insert" on sensor_logs for insert to anon with check (is_valid_device());

drop policy if exists "user read" on sensor_logs;
create policy "user read" on sensor_logs for select to authenticated using (true);

drop policy if exists "user read config" on app_config;
create policy "user read config" on app_config for select to authenticated using (true);

-- 6. Hapus otomatis data > 30 hari (hemat kuota 500 MB free tier)
create extension if not exists pg_cron;
do $$ begin perform cron.unschedule('hapus-log-lama'); exception when others then null; end $$;
select cron.schedule('hapus-log-lama', '0 17 * * *',
  $$delete from sensor_logs where created_at < now() - interval '30 days'$$);

